"""Writes port/src/install/engine_types.inc: the type trees of the Unity engine classes the on-Vita
installer reads, for the game's Unity version, plus Unity's common string table.

Usage: python -E -P gen_engine_types.py <out.inc>

Source: UnityPy's type tree database (tpk_ar, from AssetRipper's TypeTreeDumps; MIT). This is
engine metadata (Unity 2020.3 class layouts), nothing from the game.
"""
import sys
from pathlib import Path
from UnityPy.helpers import Tpk
from UnityPy.enums import ClassIDType

UNITY_VERSION = "2020.3.37f1"

CLASSES = ["GameObject", "Transform", "RectTransform", "Material", "MeshRenderer", "Texture2D", "MeshFilter", "Mesh",
           "Shader", "AudioSource", "AudioClip", "MonoBehaviour", "MonoScript", "Font", "AssetBundle",
           "ResourceManager", "SpriteRenderer", "Sprite", "AudioMixerGroupController"]


def flatten(node, out):
    out.append(node)
    for c in node.m_Children:
        flatten(c, out)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    from UnityPy.helpers.UnityVersion import UnityVersion
    version = UnityVersion.from_str(UNITY_VERSION)
    lines = ["// Generated by tools/gen_engine_types.py from UnityPy's type tree database (tpk_ar, MIT):",
             "// Unity 2020.3.37f1 engine class layouts. Do not edit.",
             "// ENGINE_TYPE(classId, \"Class\", nodeCount) then NODE(level, \"type\", \"name\", byteSize, metaFlag)...",
             ""]
    for name in CLASSES:
        cid = int(ClassIDType[name])
        nodes = []
        flatten(Tpk.get_typetree_node(cid, version), nodes)
        lines.append(f"ENGINE_TYPE({cid}, {c_str(name)}, {len(nodes)})")
        for n in nodes:
            lines.append(f"NODE({n.m_Level}, {c_str(n.m_Type)}, {c_str(n.m_Name)}, {n.m_ByteSize}, 0x{n.m_MetaFlag or 0:x})")
    # every class: its name and where its name field is (UnityPy's peek_name): 0 none, 1 first field,
    # 2 further in (needs the class's full tree above)
    lines.append("")
    lines.append("// CLASS_INFO(classId, \"Class\", nameField): 0 no m_Name, 1 m_Name first, 2 m_Name further in")
    need_tree = []
    for cid_enum in ClassIDType:
        cid = int(cid_enum)
        try:
            node = Tpk.get_typetree_node(cid, version)
        except Exception:
            continue
        mode = 0
        for i, c in enumerate(node.m_Children):
            if c.m_Name in ("m_Name", "name"):
                mode = 1 if i == 0 else 2
                break
        if mode == 2 and cid_enum.name not in CLASSES:
            need_tree.append(cid_enum.name)
        lines.append(f"CLASS_INFO({cid}, {c_str(cid_enum.name)}, {mode})")
    if need_tree:
        print("classes with m_Name further in and no tree here:", ", ".join(need_tree))
    lines.append("")
    lines.append("// Unity's common string buffer: COMMON_STRING(offset, \"string\") for type tree string offsets")
    lines.append("// with the high bit set")
    strings = Tpk.get_common_strings(version)
    for off in sorted(strings):
        lines.append(f"COMMON_STRING({off}, {c_str(strings[off])})")
    Path(sys.argv[1]).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(CLASSES)} classes, {len(strings)} common strings -> {sys.argv[1]}")


main()
